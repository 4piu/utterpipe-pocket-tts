use std::{
    collections::{BTreeMap, BTreeSet},
    fs::{self, File},
    io::{self, Read},
    path::{Component, Path, PathBuf},
    process::Command,
};

use anyhow::{Context, Result, bail};
use clap::Parser;
use serde::Deserialize;
use serde_json::{Value, json};
use sha2::{Digest, Sha256};

const PLAN_SCHEMA: &str = "utterpipe.pocket-tts.xn-release-corpus/1";
const MANIFEST_SCHEMA: &str = "utterpipe.acoustic-manifest/1";
const PROVENANCE_SCHEMA: &str = "utterpipe.pocket-tts.xn-asr-provenance/1";
const MAX_JSON_BYTES: u64 = 1_048_576;
const MAX_CASES: usize = 128;
const MAX_TRANSCRIPT_BYTES: u64 = 40_000;
const MAX_TRANSCRIPT_CODE_POINTS: usize = 10_000;
const RECOGNIZER_BATCH_SIZE: usize = 16;

#[derive(Parser, Debug)]
#[command(
    name = "utterpipe-pocket-xn-asr-corpus",
    about = "Add pinned whisper.cpp ASR evidence to an existing XN release corpus"
)]
struct Args {
    /// Checked-in XN release-corpus plan containing reference text.
    #[arg(long)]
    plan: PathBuf,
    /// Existing acoustic manifest generated by the XN corpus command.
    #[arg(long)]
    manifest: PathBuf,
    /// Pinned whisper-cli executable.
    #[arg(long)]
    recognizer: PathBuf,
    /// Pinned whisper.cpp model file.
    #[arg(long)]
    model: PathBuf,
    /// Recognizer source revision recorded in provenance.
    #[arg(long)]
    recognizer_revision: String,
    /// Stable recognizer/model profile ID recorded in provenance.
    #[arg(long, default_value = "whisper.cpp-small.en")]
    recognizer_id: String,
    /// Public model source recorded in provenance.
    #[arg(long)]
    model_source: String,
    /// New manifest path beside the input manifest. Existing files are refused.
    #[arg(long)]
    output_manifest: PathBuf,
    /// New ASR provenance JSON path. Existing files are refused.
    #[arg(long)]
    output_provenance: PathBuf,
    /// Recognizer worker threads.
    #[arg(long, default_value_t = 4)]
    threads: u32,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct CorpusPlan {
    schema: String,
    source: CorpusSource,
    asr_policy: AsrPolicy,
    voices: Vec<String>,
    seeds: Vec<u64>,
    cases: Vec<CorpusCase>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct AsrPolicy {
    maximum_wer_delta: f64,
    maximum_cer_delta: f64,
    calibrated_positive_control: String,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct CorpusSource {
    repository: String,
    revision: String,
    path: String,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct CorpusCase {
    id: String,
    tags: Vec<String>,
    text: String,
}

#[derive(Debug)]
struct ExpectedCase<'a> {
    reference: &'a str,
    candidate: PathBuf,
    baseline: PathBuf,
}

fn main() -> Result<()> {
    let args = Args::parse();
    validate_args(&args)?;
    let plan: CorpusPlan = load_bounded_json(&args.plan, "--plan")?;
    if plan.schema != PLAN_SCHEMA {
        bail!("unsupported release corpus plan schema");
    }
    validate_plan(&plan)?;

    let mut manifest: Value = load_bounded_json(&args.manifest, "--manifest")?;
    let expected = expected_cases(&plan, &args.manifest)?;
    validate_manifest(&manifest, &expected)?;

    let scratch_parent = args
        .output_manifest
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .context("--output-manifest must have an existing parent")?;
    let scratch = tempfile::Builder::new()
        .prefix(".xn-asr-")
        .tempdir_in(scratch_parent)?;
    let entries: Vec<_> = expected.iter().collect();
    let candidate_jobs = entries
        .iter()
        .enumerate()
        .map(|(index, (_, case))| {
            (
                case.candidate.clone(),
                scratch.path().join(format!("{index}-candidate")),
            )
        })
        .collect::<Vec<_>>();
    let baseline_jobs = entries
        .iter()
        .enumerate()
        .map(|(index, (_, case))| {
            (
                case.baseline.clone(),
                scratch.path().join(format!("{index}-baseline")),
            )
        })
        .collect::<Vec<_>>();
    let candidate_transcripts = transcribe_all(&args, &candidate_jobs)?;
    let baseline_transcripts = transcribe_all(&args, &baseline_jobs)?;
    let transcripts = entries
        .into_iter()
        .zip(candidate_transcripts)
        .zip(baseline_transcripts)
        .map(|(((id, case), candidate), baseline)| {
            (id.clone(), (case.reference.to_owned(), candidate, baseline))
        })
        .collect::<BTreeMap<_, _>>();

    annotate_manifest(&mut manifest, &transcripts)?;
    apply_asr_policy(&mut manifest, &plan.asr_policy)?;
    let recognizer_sha256 = sha256_file(&args.recognizer)?;
    let model_sha256 = sha256_file(&args.model)?;
    let provenance = json!({
        "schema":PROVENANCE_SCHEMA,
        "recognizer":{
            "id":args.recognizer_id,
            "repository":"ggml-org/whisper.cpp",
            "revision":args.recognizer_revision,
            "executable_sha256":recognizer_sha256
        },
        "model":{
            "source":args.model_source,
            "sha256":model_sha256
        },
        "language":"en",
        "decoding":{
            "temperature":0.0,
            "beam_size":5,
            "best_of":5,
            "threads":args.threads
        },
        "case_count":expected.len(),
        "audio_per_case":["candidate-a","baseline"],
        "policy":{
            "maximum_wer_delta":plan.asr_policy.maximum_wer_delta,
            "maximum_cer_delta":plan.asr_policy.maximum_cer_delta,
            "calibrated_positive_control":plan.asr_policy.calibrated_positive_control
        }
    });

    persist_json(&args.output_provenance, &provenance)?;
    if let Err(error) = persist_json(&args.output_manifest, &manifest) {
        let _ = fs::remove_file(&args.output_provenance);
        return Err(error);
    }
    eprintln!("annotated {} cases", expected.len());
    Ok(())
}

fn validate_args(args: &Args) -> Result<()> {
    for (label, path) in [
        ("--plan", &args.plan),
        ("--manifest", &args.manifest),
        ("--recognizer", &args.recognizer),
        ("--model", &args.model),
    ] {
        require_absolute_regular(label, path)?;
    }
    for (label, path) in [
        ("--output-manifest", &args.output_manifest),
        ("--output-provenance", &args.output_provenance),
    ] {
        if !path.is_absolute() || path.exists() {
            bail!("{label} must be an absent absolute path");
        }
        if !path.parent().is_some_and(Path::is_dir) {
            bail!("{label} must have an existing parent directory");
        }
    }
    if args.output_manifest == args.output_provenance {
        bail!("ASR manifest and provenance outputs must differ");
    }
    if !(1..=256).contains(&args.threads) {
        bail!("--threads must be in 1..=256");
    }
    for (label, value) in [
        ("--recognizer-id", args.recognizer_id.as_str()),
        ("--recognizer-revision", args.recognizer_revision.as_str()),
        ("--model-source", args.model_source.as_str()),
    ] {
        if value.is_empty() || value.chars().count() > 2048 || value.chars().any(char::is_control) {
            bail!("{label} must be nonempty, bounded, and contain no control characters");
        }
    }
    Ok(())
}

fn validate_plan(plan: &CorpusPlan) -> Result<()> {
    if plan.voices.is_empty()
        || plan.seeds.is_empty()
        || plan.cases.is_empty()
        || plan.cases.len() * plan.voices.len() * plan.seeds.len() > MAX_CASES
        || plan.voices.iter().collect::<BTreeSet<_>>().len() != plan.voices.len()
        || plan.seeds.iter().collect::<BTreeSet<_>>().len() != plan.seeds.len()
        || plan
            .cases
            .iter()
            .map(|case| &case.id)
            .collect::<BTreeSet<_>>()
            .len()
            != plan.cases.len()
    {
        bail!("release corpus plan dimensions or IDs are invalid");
    }
    if plan.source.repository.is_empty()
        || plan.source.revision.is_empty()
        || plan.source.path.is_empty()
    {
        bail!("release corpus source provenance is incomplete");
    }
    if !plan.asr_policy.maximum_wer_delta.is_finite()
        || plan.asr_policy.maximum_wer_delta < 0.0
        || !plan.asr_policy.maximum_cer_delta.is_finite()
        || plan.asr_policy.maximum_cer_delta < 0.0
        || plan.asr_policy.calibrated_positive_control.is_empty()
        || plan.asr_policy.calibrated_positive_control.chars().count() > 80
    {
        bail!("release corpus ASR policy is invalid");
    }
    for case in &plan.cases {
        if case.text.is_empty()
            || case.text.chars().count() > MAX_TRANSCRIPT_CODE_POINTS
            || case.tags.is_empty()
        {
            bail!("release corpus text or tags are invalid");
        }
    }
    Ok(())
}

fn expected_cases<'a>(
    plan: &'a CorpusPlan,
    manifest_path: &Path,
) -> Result<BTreeMap<String, ExpectedCase<'a>>> {
    let root = manifest_path
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .context("--manifest must have a parent directory")?;
    let mut expected = BTreeMap::new();
    for voice in &plan.voices {
        for seed in &plan.seeds {
            for case in &plan.cases {
                let id = format!("{}-{voice}-seed{seed}", case.id);
                expected.insert(
                    id.clone(),
                    ExpectedCase {
                        reference: &case.text,
                        candidate: root.join(format!("audio/{id}-candidate-a.wav")),
                        baseline: root.join(format!("audio/{id}-baseline.wav")),
                    },
                );
            }
        }
    }
    Ok(expected)
}

fn validate_manifest(
    manifest: &Value,
    expected: &BTreeMap<String, ExpectedCase<'_>>,
) -> Result<()> {
    if manifest["schema"] != MANIFEST_SCHEMA {
        bail!("unsupported acoustic manifest schema");
    }
    let cases = manifest["cases"]
        .as_array()
        .context("acoustic manifest cases must be an array")?;
    if cases.len() != expected.len() {
        bail!("acoustic manifest does not exactly match the release plan");
    }
    let mut found = BTreeSet::new();
    for case in cases {
        let id = case["id"].as_str().context("manifest case ID is missing")?;
        let expected_case = expected
            .get(id)
            .context("manifest contains a case outside the release plan")?;
        if case.get("transcripts").is_some()
            || case["candidate_wavs"]
                .as_array()
                .and_then(|paths| paths.first())
                .and_then(Value::as_str)
                != expected_case
                    .candidate
                    .file_name()
                    .and_then(|name| name.to_str())
                    .map(|name| format!("audio/{name}"))
                    .as_deref()
            || case["baseline_wavs"]
                .as_array()
                .and_then(|paths| paths.first())
                .and_then(Value::as_str)
                != expected_case
                    .baseline
                    .file_name()
                    .and_then(|name| name.to_str())
                    .map(|name| format!("audio/{name}"))
                    .as_deref()
            || !found.insert(id)
        {
            bail!("manifest case layout is not the expected unannotated corpus");
        }
        require_absolute_regular("candidate WAV", &expected_case.candidate)?;
        require_absolute_regular("baseline WAV", &expected_case.baseline)?;
    }
    Ok(())
}

fn transcribe_all(args: &Args, jobs: &[(PathBuf, PathBuf)]) -> Result<Vec<String>> {
    for (batch_index, batch) in jobs.chunks(RECOGNIZER_BATCH_SIZE).enumerate() {
        eprintln!("transcribing ASR batch {}", batch_index + 1);
        let mut command = Command::new(&args.recognizer);
        command
            .args(["--model"])
            .arg(&args.model)
            .args([
                "--language",
                "en",
                "--output-txt",
                "--no-timestamps",
                "--no-prints",
            ])
            .args(["--threads", &args.threads.to_string()])
            .args(["--temperature", "0", "--beam-size", "5", "--best-of", "5"]);
        for (wav, prefix) in batch {
            command
                .args(["--file"])
                .arg(wav)
                .args(["--output-file"])
                .arg(prefix);
        }
        let output = command.output()?;
        if !output.status.success() {
            bail!("recognizer failed with status {}", output.status);
        }
    }

    jobs.iter()
        .map(|(_, output_prefix)| read_transcript(output_prefix))
        .collect()
}

fn read_transcript(output_prefix: &Path) -> Result<String> {
    let text_path = output_prefix.with_extension("txt");
    let metadata = fs::symlink_metadata(&text_path)?;
    if !metadata.file_type().is_file() || metadata.len() > MAX_TRANSCRIPT_BYTES {
        bail!("recognizer transcript is not a bounded regular file");
    }
    let transcript = fs::read_to_string(&text_path)?;
    let transcript = transcript.trim();
    if transcript.is_empty() || transcript.chars().count() > MAX_TRANSCRIPT_CODE_POINTS {
        bail!("recognizer transcript is empty or too large");
    }
    Ok(transcript.to_owned())
}

fn annotate_manifest(
    manifest: &mut Value,
    transcripts: &BTreeMap<String, (String, String, String)>,
) -> Result<()> {
    let cases = manifest["cases"]
        .as_array_mut()
        .context("acoustic manifest cases must be an array")?;
    for case in cases {
        let id = case["id"].as_str().context("manifest case ID is missing")?;
        let (reference, candidate, baseline) = transcripts
            .get(id)
            .context("ASR transcript set does not match manifest")?;
        case.as_object_mut()
            .context("manifest case must be an object")?
            .insert(
                "transcripts".to_owned(),
                json!({
                    "reference":reference,
                    "candidate_asr":candidate,
                    "baseline_asr":baseline
                }),
            );
    }
    Ok(())
}

fn apply_asr_policy(manifest: &mut Value, policy: &AsrPolicy) -> Result<()> {
    let requirements = manifest["requirements"]
        .as_object_mut()
        .context("acoustic manifest requirements must be an object")?;
    requirements.insert("require_transcripts".to_owned(), json!(true));
    let manifest_policy = manifest["policy"]
        .as_object_mut()
        .context("acoustic manifest policy must be an object")?;
    manifest_policy.insert(
        "maximum_wer_delta".to_owned(),
        json!(policy.maximum_wer_delta),
    );
    manifest_policy.insert(
        "maximum_cer_delta".to_owned(),
        json!(policy.maximum_cer_delta),
    );
    Ok(())
}

fn load_bounded_json<T: serde::de::DeserializeOwned>(path: &Path, label: &str) -> Result<T> {
    let metadata = fs::symlink_metadata(path)?;
    if !metadata.file_type().is_file() || metadata.len() > MAX_JSON_BYTES {
        bail!("{label} must be a bounded regular JSON file");
    }
    Ok(serde_json::from_slice(&fs::read(path)?)?)
}

fn require_absolute_regular(label: &str, path: &Path) -> Result<()> {
    if !path.is_absolute()
        || path
            .components()
            .any(|part| matches!(part, Component::ParentDir))
        || !fs::symlink_metadata(path).is_ok_and(|metadata| metadata.file_type().is_file())
    {
        bail!("{label} must be an existing absolute regular file");
    }
    Ok(())
}

fn sha256_file(path: &Path) -> Result<String> {
    let mut input = File::open(path)?;
    let mut hasher = Sha256::new();
    io::copy(&mut input.by_ref().take(u64::MAX), &mut hasher)?;
    Ok(format!("{:x}", hasher.finalize()))
}

fn persist_json(path: &Path, value: &Value) -> Result<()> {
    let parent = path.parent().context("output must have a parent")?;
    let mut temp = tempfile::Builder::new()
        .prefix(".xn-asr-json-")
        .tempfile_in(parent)?;
    serde_json::to_writer_pretty(temp.as_file_mut(), value)?;
    temp.persist_noclobber(path)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn annotation_matches_by_case_id_without_echoing_paths() {
        let mut manifest = json!({
            "schema":MANIFEST_SCHEMA,
            "requirements":{},
            "policy":{},
            "cases":[{"id":"case-a"},{"id":"case-b"}]
        });
        let transcripts = BTreeMap::from([
            (
                "case-a".to_owned(),
                ("A".to_owned(), "a".to_owned(), "a".to_owned()),
            ),
            (
                "case-b".to_owned(),
                ("B".to_owned(), "b".to_owned(), "b".to_owned()),
            ),
        ]);
        annotate_manifest(&mut manifest, &transcripts).unwrap();
        apply_asr_policy(
            &mut manifest,
            &AsrPolicy {
                maximum_wer_delta: 0.15,
                maximum_cer_delta: 0.07,
                calibrated_positive_control: "known-bad".to_owned(),
            },
        )
        .unwrap();
        assert_eq!(manifest["cases"][1]["transcripts"]["reference"], "B");
        assert_eq!(manifest["requirements"]["require_transcripts"], true);
        assert_eq!(manifest["policy"]["maximum_wer_delta"], 0.15);
        assert!(!manifest.to_string().contains("/private/"));
    }
}
